<h2>1. Who this applies to</h2>
<p>This Privacy Policy explains how Gaurangi Technologies ("we", "us", "the Platform") collects, stores and
processes data on behalf of {{ $institute->name ?? 'your institute' }} ("the Institute") when the Institute uses this
multi-tenant college/institute management system ("the Service"). The Institute acts as the data controller for the
student, staff and financial records it enters; we act as a data processor acting on the Institute's instructions.</p>

<h2>2. Data we store on your behalf</h2>
<p>Depending on the modules the Institute enables, this may include: student and guardian personal details, admission
and academic records, fee and payment records, staff and payroll records, attendance data, documents uploaded by the
Institute or applicants, and communication logs (SMS/email/WhatsApp sent through the platform).</p>

<h2>3. Tenant isolation</h2>
<p>Each Institute's data is logically separated from every other Institute on the platform using a unique institute
identifier enforced at the database and application layer. Staff of one Institute cannot access another Institute's
records through the Service.</p>

<h2>4. How we use the data</h2>
<ul>
    <li>To operate the features the Institute has subscribed to (admission, fees, attendance, reports, etc.)</li>
    <li>To send OTPs, notices and transactional communication the Institute triggers</li>
    <li>To provide support and troubleshoot issues raised by the Institute</li>
    <li>To maintain security logs and detect misuse</li>
</ul>
<p>We do not sell Institute or student data, and we do not use it for advertising.</p>

<h2>5. Third-party sub-processors</h2>
<p>We may use third-party providers for email delivery, SMS/OTP delivery, payment gateway processing and cloud
hosting/backups, strictly to operate the Service. These providers are bound by confidentiality and data-processing
obligations.</p>

<h2>6. Data retention &amp; deletion</h2>
<p>Institute data is retained for as long as the subscription is active, plus a limited grace period after
expiry/termination to allow export. After that period, data may be permanently deleted from production systems
unless retention is required by applicable law. The Institute may request an export or early deletion at any time.</p>

<h2>7. Security measures</h2>
<p>We apply access controls, encrypted credential storage, encrypted connections (HTTPS), and role-based access
within the Institute's own account. No system is 100% secure; the Institute is responsible for safeguarding staff
login credentials issued to its own users.</p>

<h2>8. Institute &amp; data-subject rights</h2>
<p>The Institute may access, correct or export the data it has entered at any time through the platform. Students,
staff or guardians who wish to exercise data rights (access, correction, deletion) should contact the Institute
directly, as the Institute is the data controller; the Institute may in turn raise this with us.</p>

<h2>9. Breach notification</h2>
<p>In the event of a data breach affecting the Institute's data, we will notify the Institute without undue delay
after becoming aware of it, along with the nature of the breach and mitigation steps taken.</p>

<h2>10. Changes to this policy</h2>
<p>We may update this Privacy Policy from time to time. Material changes will require re-acceptance before continued
use of the Service.</p>

<h2>11. Contact</h2>
<p>For privacy-related queries, contact Gaurangi Technologies through the support channel provided at onboarding.</p>
